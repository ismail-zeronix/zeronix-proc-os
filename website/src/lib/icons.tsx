import { createElement } from "react";
import {
  BadgeCheck,
  Briefcase,
  Building2,
  Cctv,
  Circle,
  Clapperboard,
  Cpu,
  GraduationCap,
  HardHat,
  Headphones,
  Headset,
  Hotel,
  IdCard,
  Keyboard,
  KeyRound,
  Landmark,
  Laptop,
  Layers,
  Monitor,
  Network,
  Package,
  PackageCheck,
  PenTool,
  Phone,
  Presentation,
  Receipt,
  Scale,
  Server,
  ShieldCheck,
  ShoppingBag,
  Stethoscope,
  Truck,
  Users,
  Wifi,
  Zap,
  type LucideIcon,
  type LucideProps,
} from "lucide-react";
import type { SiteIcon } from "./contract";

/** The icon names editors pick in the portal (SITE_ICONS) as components; unknown or empty names get a plain dot. */
const ICONS: Record<SiteIcon, LucideIcon> = {
  building: Building2,
  "pen-tool": PenTool,
  "hard-hat": HardHat,
  scale: Scale,
  stethoscope: Stethoscope,
  landmark: Landmark,
  "graduation-cap": GraduationCap,
  hotel: Hotel,
  truck: Truck,
  clapperboard: Clapperboard,
  "shopping-bag": ShoppingBag,
  briefcase: Briefcase,
  laptop: Laptop,
  monitor: Monitor,
  cpu: Cpu,
  server: Server,
  "shield-check": ShieldCheck,
  "badge-check": BadgeCheck,
  headset: Headset,
  "package-check": PackageCheck,
  receipt: Receipt,
  zap: Zap,
  users: Users,
  network: Network,
  layers: Layers,
  wifi: Wifi,
  cctv: Cctv,
  "id-card": IdCard,
  presentation: Presentation,
  phone: Phone,
  headphones: Headphones,
  keyboard: Keyboard,
  "key-round": KeyRound,
  package: Package,
};

export const iconFor = (name: string): LucideIcon => ICONS[name as SiteIcon] ?? Circle;

/** Renders an editor-picked icon by name (keeps dynamic component lookups out of render bodies). */
export function SiteIconView({ name, ...props }: { name: string } & LucideProps) {
  return createElement(iconFor(name), props);
}
