"use client";

import { type Brand, type Person, signatureHtml } from "@/lib/signature";

/** What the signature looks like in an email: always on white, as the recipient will see it. */
export function SignaturePreview({ brand, person, logoSrc }: { brand: Brand; person: Person; logoSrc: string }) {
  return (
    <div className="overflow-x-auto rounded-lg border bg-white p-4 text-neutral-900">
      <div className="mb-3 text-sm text-neutral-500">Kind regards,</div>
      {/* generated by signatureHtml(), which escapes every field */}
      <div dangerouslySetInnerHTML={{ __html: signatureHtml(brand, person, logoSrc) }} />
    </div>
  );
}
